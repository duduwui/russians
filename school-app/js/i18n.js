function _safeGet(k) { try { return localStorage.getItem(k); } catch (e) { return null; } }
function _safeSet(k,v){ try { localStorage.setItem(k,v); } catch (e) {} }

const i18n = {
  lang: _safeGet("app.lang") || "en",
  t(key) { return (I18N[this.lang] && I18N[this.lang][key]) || I18N.en[key] || key; },
  setLang(lang) {
    this.lang = lang;
    _safeSet("app.lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    this.apply();
    if (window.App && window.App.rerender) window.App.rerender();
  },
  apply() {
    document.querySelectorAll("[data-i18n]").forEach(el => {
      el.textContent = this.t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(el => {
      el.setAttribute("placeholder", this.t(el.getAttribute("data-i18n-ph")));
    });
    document.querySelectorAll(".lang-switch button").forEach(b => {
      b.classList.toggle("active", b.dataset.lang === this.lang);
    });
  }
};
